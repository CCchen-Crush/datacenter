function [row, hdr] = metrics_row(M)
%METRICS_ROW  Flatten the evaluation struct into a numeric row (for tables / CSV).
hdr = {'fulfil_rate_pct', 'n_valid', 'red_E1', 'red_E2', 'red_E3', 'rebound_E1', 'rebound_E2', 'rebound_E3', ...
       'max_rebound_MW', 'E_start_E1', 'E_start_E2', 'E_start_E3', 'B_start_E1', 'B_start_E2', 'B_start_E3', ...
       'cost_energy', 'cost_gas', 'cost_deg', 'cost_op', 'dr_pay', 'pen_dev', 'pen_rb', 'net_cost', ...
       'lateness_GPUh_h', 'peak_grid_MW', 'cap_violation_MW', 'bess_throughput_MWh', 'solve_time_s', 'fallbacks'};
K = numel(M.avg_red); pad = @(v) [v(:)' nan(1, 3 - numel(v))];
row = [100 * M.fulfil_rate, M.n_valid, pad(M.avg_red(1:min(3,K))), pad(M.rebound(1:min(3,K))), M.max_rebound, ...
       pad(M.E_start(1:min(3,K))), pad(sum(M.B_start(1:min(3,K), :), 2)), ...
       M.cost_energy, M.cost_gas, M.cost_deg, M.cost_op, M.dr_pay, M.pen_dev, M.pen_rb, M.net_cost, ...
       M.lateness, M.peak_grid, M.cap_violation, M.bess_throughput, M.solve_time, M.fallbacks];
end
